export function localeForCurrency(code: string) {
  const map: Record<string, string> = {
    USD: "en-US",
    EUR: "en-IE",
    GBP: "en-GB",
    NGN: "en-NG",
    CAD: "en-CA",
    AUD: "en-AU",
    JPY: "ja-JP",
    INR: "en-IN",
    AED: "en-AE",
    ZAR: "en-ZA",
    GHS: "en-GH",
    KES: "en-KE",
  };
  return map[code] || "en-US";
}

export function fractionDigitsFor(code: string) {
  if (ZERO_DECIMAL.has(code)) return 0;
  if (code === "NGN") return 0;
  return 2;
}

export function isKnownCurrency(code: string) {
  return WORLD_CURRENCIES.some((c) => c.code === code);
}
